"""Backtest: replays the rules weekly across W39-W42 using only the sales available
at each point, plus a sensitivity table. Writes docs/backtest.md.

    python -m src.jobs.backtest
"""
from __future__ import annotations

from collections import Counter
from datetime import timedelta

import pandas as pd

from src.connectors.csv_folder import CsvFolderConnector
from src.engine.pipeline import run_engine
from src.engine.weeks import week_start
from src.rules_config import load_default_rules
from src.settings import ROOT

REPLAY_WEEKS = ["2026-W39", "2026-W40", "2026-W41", "2026-W42"]
SHORT = {"STOCKOUT_RISK": "STOCKOUT", "OVERSTOCK_RISK": "OVERSTOCK", "HIGH_DEMAND": "HIGH_DEMAND",
         "OK": "OK", "EXCEPTION": "EXCEPTION"}
STATUSES = ["STOCKOUT_RISK", "HIGH_DEMAND", "OVERSTOCK_RISK", "EXCEPTION", "OK"]


def run_date_for(week: str):
    """The Thursday after the week ends (W42 -> 2026-10-22, the golden run date)."""
    return week_start(week) + timedelta(days=10)


def replay(raw, rules):
    out = {}
    for week in REPLAY_WEEKS:
        res = run_engine(raw, run_date_for(week), rules)
        assert res.data_week == week
        out[week] = res.recommendations.set_index("sku_id")
    return out


def build_report() -> str:
    raw = CsvFolderConnector(ROOT / "data").fetch()
    rules = load_default_rules()
    results = replay(raw, rules)
    skus = list(results[REPLAY_WEEKS[-1]].index)

    lines = ["# Backtest", "",
             "Generated by `python -m src.jobs.backtest` from the 5 sample CSVs. Each column is a simulated "
             "Thursday run that sees only the sales up to that week. All four runs fall in October (a festival "
             "month), so the +25% uplift applies to every column.", "",
             "## 1. Flags week by week (cover in weeks)", "",
             "| SKU | Perishable | " + " | ".join(REPLAY_WEEKS) + " |",
             "|---|---|" + "---|" * len(REPLAY_WEEKS)]
    for sku in skus:
        cells = []
        for w in REPLAY_WEEKS:
            r = results[w].loc[sku]
            flags = "+".join(SHORT[f] for f in r["flags"]) or "OK"
            cells.append(f"{flags} ({r['cover_weeks']})")
        lines.append(f"| {sku} | {'yes' if results[REPLAY_WEEKS[-1]].loc[sku, 'perishable'] else 'no'} | "
                     + " | ".join(cells) + " |")

    changed = [s for s in skus if len({tuple(results[w].loc[s, 'flags']) for w in REPLAY_WEEKS}) > 1]
    lines += ["", f"SKUs whose flags changed across the four weeks: {', '.join(changed) or 'none'}.", ""]

    # SKU001 deep dive
    sales = raw["weekly_sales"]
    s1 = sales[sales.SKU_ID == "SKU001"].set_index("Week")["Units_Sold"].astype(int)
    lines += ["## 2. Key case: SKU001 demand jump", "",
              f"Weekly sales W35-W38: {', '.join(str(s1[f'2026-W{w}']) for w in range(35, 39))}. "
              f"W39-W42: {', '.join(str(s1[f'2026-W{w}']) for w in range(39, 43))}. "
              "Sales stepped up about 40% at W39 and stayed there.", "",
              "| Run sees up to | avg4 | avg12 | avg4 / avg12 | HIGH_DEMAND (>1.20)? | Cover | Status | Qty |",
              "|---|---|---|---|---|---|---|---|"]
    for w in REPLAY_WEEKS:
        r = results[w].loc["SKU001"]
        ratio = r["avg4"] / r["avg12"]
        lines.append(f"| {w} | {r['avg4']} | {r['avg12']} | {ratio:.3f} | "
                     f"{'yes' if 'HIGH_DEMAND' in r['flags'] else 'no'} | {r['cover_weeks']} | {r['status']} | "
                     f"{r['recommended_qty'] if r['recommended_qty'] is not None else '—'} |")
    lines += ["",
              "**Finding:** the high-demand rule compares a 4-week average with a 12-week average that already "
              "contains those 4 weeks, so a sustained step change only crosses the 1.20 threshold in the fourth "
              "week after it starts (W42). The stockout rule caught SKU001 from the first replayed run, so the "
              "reorder was never missed, but for three runs it recommended the standard 500 units instead of 750. "
              "Raghav may want to review the 1.20 threshold or compare avg4 with the 12 weeks *before* them.", ""]

    # Sensitivity
    lines += ["## 3. Sensitivity (counts of SKUs per status)", "",
              "Demand baseline = which average feeds weekly demand and cover. The rule definition uses avg12.", "",
              "| Run | Demand baseline | Festival uplift | " + " | ".join(STATUSES) + " |",
              "|---|---|---|" + "---|" * len(STATUSES)]
    changes = []
    for week in (REPLAY_WEEKS[0], REPLAY_WEEKS[-1]):
        base = None
        for baseline in ("long", "short"):
            for uplift in (True, False):
                r = load_default_rules()
                r.windows.demand_baseline = baseline
                r.festival.enabled = uplift
                res = run_engine(raw, run_date_for(week), r).recommendations.set_index("sku_id")
                c = Counter(res["status"])
                label = f"{'avg12' if baseline == 'long' else 'avg4'} baseline, uplift {'on' if uplift else 'off'}"
                lines.append(f"| {week} | {'avg12' if baseline == 'long' else 'avg4'} | {'on' if uplift else 'off'} | "
                             + " | ".join(str(c.get(s, 0)) for s in STATUSES) + " |")
                if base is None:
                    base = res
                    continue
                diff = [f"{s} {base.loc[s, 'status']} → {res.loc[s, 'status']} ({res.loc[s, 'cover_weeks']} wks)"
                        for s in res.index if res.loc[s, "status"] != base.loc[s, "status"]]
                changes.append(f"- {week}, {label}: " + ("; ".join(diff) if diff else "no change"))
    lines += ["", "Changes compared with the standard setting (avg12 baseline, uplift on) for the same run:", "",
              *changes, ""]

    lines += ["## 4. What this backtest cannot validate", "",
              "- **Stock history.** There is one inventory snapshot (as of 2026-10-19). Every replayed run uses "
              "that same stock figure, so the cover numbers for W39-W41 are not what the business actually had "
              "then. The flags show how the *sales signal* evolved, not real past decisions.",
              "- **Festival uplift accuracy.** The sample has 16 weeks (W27-W42, July to mid-October 2026). The "
              "only festival month it touches is October 2026, which is only partly observed, and there is no "
              "earlier festival period to compare against. Whether +25% is the right uplift cannot be tested "
              "with this data.",
              "- **Outcomes.** There is no record of what was actually ordered, delivered or stocked out, so the "
              "backtest cannot score the recommendations as right or wrong.",
              "- **Open purchase orders.** Zoho is not connected yet, so stock already on order is not counted in "
              "cover. A SKU with a large PO arriving next week may be flagged as a stockout risk.",
              "- **Scale.** The sample has 15 SKUs and 4 distributors. Performance at real scale is covered "
              "separately by a synthetic 400 SKU x 156 week test, not by real data.",
              "- **Forecasting.** No forecasting model was built or tested. Sixteen weeks of history cannot support "
              "one; it remains a future option once more history exists.", ""]
    return "\n".join(lines)


def main() -> None:
    report = build_report()
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "backtest.md").write_text(report, encoding="utf-8")
    print(f"Wrote docs/backtest.md ({len(report.splitlines())} lines)")


if __name__ == "__main__":
    main()
